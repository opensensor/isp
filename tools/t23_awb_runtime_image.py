#!/usr/bin/env python3
"""Generate the T23 SC2336 runtime AWB tables used by the active HLIL path."""

from __future__ import annotations

import argparse
import hashlib
import struct
from pathlib import Path


TUNING_HEADER_SIZE = 0x18

OFFSETS = {
    "pixel_count_threshold": (0x10C4, 1),
    "point_position": (0x10D0, 2),
    "history_control": (0x10D8, 2),
    "mf_parameters": (0x10E0, 6),
    "mode": (0x10F8, 3),
    "ct": (0x1104, 1),
    "wb_static": (0x110C, 2),
    "light_sources": (0x1114, 20),
    "light_source_count": (0x1164, 1),
    "rg_positions": (0x1168, 15),
    "bg_positions": (0x11A4, 15),
    "ct_parameters_outdoor": (0x1210, 2),
    "ct_parameters_indoor": (0x1218, 2),
    "distance_parameters": (0x1220, 3),
    "indoor_ct_weight_mesh": (0x122C, 225),
    "color_temperature_mesh": (0x15B0, 225),
    "zone_weight_mesh": (0x1934, 225),
    "outdoor_ct_weight_mesh": (0x1CB8, 225),
    "light_source_weight_lut": (0x203C, 514),
    "cluster_parameters": (0x284C, 10),
}


def read_words(blob: bytes, offset: int, count: int) -> tuple[int, ...]:
    return struct.unpack_from(f"<{count}I", blob, TUNING_HEADER_SIZE + offset)


def emit_array(name: str, values: tuple[int, ...]) -> list[str]:
    lines = [f"static const uint32_t {name}[{len(values)}] = {{"]
    for index in range(0, len(values), 8):
        row = ", ".join(f"0x{value:08x}U" for value in values[index : index + 8])
        lines.append(f"    {row},")
    lines.append("};")
    return lines


def render(path: Path) -> str:
    blob = path.read_bytes()
    values = {
        name: read_words(blob, offset, count)
        for name, (offset, count) in OFFSETS.items()
    }

    point_position = values["point_position"]
    mode = values["mode"]
    cluster = values["cluster_parameters"]
    light_source_count = values["light_source_count"][0]

    if point_position[0] != 10:
        raise ValueError(f"unexpected AWB fixed-point position: {point_position!r}")
    if tuple(sorted(values["rg_positions"])) != values["rg_positions"]:
        raise ValueError("AWB rg position table is not sorted")
    if tuple(sorted(values["bg_positions"])) != values["bg_positions"]:
        raise ValueError("AWB bg position table is not sorted")
    if not (mode[0] < mode[1] < mode[2]):
        raise ValueError(f"unexpected AWB mode thresholds: {mode!r}")
    if cluster[0] != 0:
        raise ValueError(f"SC2336 AWB cluster mode is unexpectedly enabled: {cluster!r}")
    if values["ct_parameters_outdoor"][0] != 0:
        raise ValueError(
            "SC2336 outdoor AWB CT edge weighting is unexpectedly enabled"
        )
    if values["ct_parameters_indoor"][0] != 0:
        raise ValueError(
            "SC2336 indoor AWB CT edge weighting is unexpectedly enabled"
        )
    if values["distance_parameters"][0] != 1:
        raise ValueError("SC2336 AWB distance refinement is unexpectedly disabled")
    if not 0 < light_source_count <= 10:
        raise ValueError(
            f"unexpected AWB light-source count: {light_source_count}"
        )

    lines = [
        "/* Generated by tools/t23_awb_runtime_image.py. */",
        f"/* Source tuning SHA256: {hashlib.sha256(blob).hexdigest()} */",
        "/* Runtime selects the outdoor or indoor CT mesh from the live EV. */",
        f"#define REGTRACE_T23_AWB_HLIL_PIXEL_THRESHOLD {values['pixel_count_threshold'][0]}U",
        f"#define REGTRACE_T23_AWB_HLIL_POINT_POSITION {point_position[0]}U",
        f"#define REGTRACE_T23_AWB_HLIL_HISTORY_WINDOW {values['history_control'][0]}U",
        "#define REGTRACE_T23_AWB_HLIL_STARTUP_EV (400U << 10)",
        f"#define REGTRACE_T23_AWB_HLIL_STARTUP_CT {values['ct'][0]}U",
        f"#define REGTRACE_T23_AWB_HLIL_OUTDOOR_EV {mode[0]}U",
        f"#define REGTRACE_T23_AWB_HLIL_INDOOR_EV {mode[1]}U",
        f"#define REGTRACE_T23_AWB_HLIL_LIGHT_SOURCE_COUNT {light_source_count}U",
        "",
    ]

    emitted = (
        ("regtrace_t23_awb_hlil_mf_parameters", "mf_parameters"),
        ("regtrace_t23_awb_hlil_wb_static", "wb_static"),
        ("regtrace_t23_awb_hlil_light_sources", "light_sources"),
        ("regtrace_t23_awb_hlil_rg_positions", "rg_positions"),
        ("regtrace_t23_awb_hlil_bg_positions", "bg_positions"),
        ("regtrace_t23_awb_hlil_distance_parameters", "distance_parameters"),
        ("regtrace_t23_awb_hlil_indoor_ct_weight_mesh", "indoor_ct_weight_mesh"),
        ("regtrace_t23_awb_hlil_color_temperature_mesh", "color_temperature_mesh"),
        ("regtrace_t23_awb_hlil_zone_weight_mesh", "zone_weight_mesh"),
        ("regtrace_t23_awb_hlil_outdoor_ct_weight_mesh", "outdoor_ct_weight_mesh"),
        ("regtrace_t23_awb_hlil_light_source_weight_lut", "light_source_weight_lut"),
    )
    for c_name, value_name in emitted:
        lines.extend(emit_array(c_name, values[value_name]))
        lines.append("")

    return "\n".join(lines)


def main() -> None:
    parser = argparse.ArgumentParser()
    parser.add_argument("tuning_blob", type=Path)
    parser.add_argument("-o", "--output", type=Path)
    args = parser.parse_args()
    output = render(args.tuning_blob)
    if args.output:
        args.output.write_text(output, encoding="ascii")
    else:
        print(output, end="")


if __name__ == "__main__":
    main()
