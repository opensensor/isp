	E(0xa224,W(0x56)); E(0xa228,S(0x62)<<16 | T(0x60)); E(0xa22c,T(0x6c)<<16 | T(0x6e));
	E(0xa230,((S(0x71)<<4)+15)<<16 | S(0x70)<<4); E(0xa234,W(0x68));
